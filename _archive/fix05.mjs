// payload.txt parho (BOM tolerant — recv.mjs jaisa hi)
const rawFile = fs.readFileSync(PAYLOAD);
let text;
if (rawFile[0] === 0xff && rawFile[1] === 0xfe) text = new TextDecoder("utf-16le").decode(rawFile.subarray(2));
else if (rawFile[0] === 0xef && rawFile[1] === 0xbb && rawFile[2] === 0xbf) text = rawFile.subarray(3).toString("utf8");
else text = rawFile.toString("utf8");

// PURGE: har CHUNK-05 block (marker + content) hatao — chahe jitne bhi hon
const out = [];
let cur = null;
let removedBlocks = 0;
let removedLines = 0;
for (const rl of text.split(/\r?\n/)) {
  const line = rl.trim();
  if (line.length === 0) continue;
  const m = line.match(/^===CHUNK-(\d+)===$/);
  if (m) {
    cur = m[1].padStart(2, "0");
    if (cur === "05") removedBlocks++;
  }
  if (cur === "05") { removedLines++; continue; }
  out.push(line);
}
console.log("Purane CHUNK-05 blocks hataye: " + removedBlocks + "  (" + removedLines + " lines saaf)");

// Naya canonical CHUNK-05 file ke aakhir mein jama karo
out.push("===CHUNK-05===");
for (const L of lines) out.push(L);
fs.writeFileSync(PAYLOAD, out.join("\r\n") + "\r\n", "utf8");

