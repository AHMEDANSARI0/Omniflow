def origin(name):
    return tuple(float(v) for v in re.search(r"transform-origin: ([\d.]+)% ([\d.]+)%;", rule(name)).groups())


def bezier(spec):
    x1, y1, x2, y2 = spec

    def ease(x):
        lo, hi = 0.0, 1.0
        for _ in range(40):
            t = (lo + hi) / 2
            if 3 * (1 - t) ** 2 * t * x1 + 3 * (1 - t) * t * t * x2 + t ** 3 < x:
                lo = t
            else:
                hi = t
        t = (lo + hi) / 2
        return 3 * (1 - t) ** 2 * t * y1 + 3 * (1 - t) * t * t * y2 + t ** 3
    return ease


SWING = bezier((0.37, 0, 0.23, 1))


def simulate(side, poses):
    """fingertip speed (canvas heights / s), sideways forearm length, hand stretch (forearm k and wrist 1/k interpolate apart),
    and how far the OPEN palm's fingers ever point sideways (|sin| of the hand direction)."""
    import math
    W, H = 560, 846
    suf = side.upper()
    S, E, Wr = [(x / 100 * W, y / 100 * H) for x, y in (origin(".arm" + suf), origin(".fore" + suf), origin(".hand" + suf))]
    poses = [(0, *motion.REST)] + list(poses) + [(motion.LOOP, *motion.REST)]
    ts = [p[0] for p in poses]
    timings = getattr(motion, "timings", lambda ts, vs: {})  # before 253 every segment eased on its own
    shoulder, elbow = timings(ts, [p[1] for p in poses]), timings(ts, [p[2] for p in poses])
    curve = lambda tim, t0: bezier(tuple(map(float, tim[t0][13:-1].split(", ")))) if t0 in tim else SWING
    rot = lambda v, d: (v[0] * math.cos(math.radians(d)) - v[1] * math.sin(math.radians(d)), v[0] * math.sin(math.radians(d)) + v[1] * math.cos(math.radians(d)))
    about = lambda o, p, fn: (lambda v: (o[0] + v[0], o[1] + v[1]))(fn((p[0] - o[0], p[1] - o[1])))
    speed = sideways = stretch = palm_side = 0.0
    windows = motion.PALM.get(side, [])
    fade = getattr(motion, "FADE", 0)
    prev = None
    for i in range(int(motion.LOOP * 120) + 1):
        t = i / 120
        for (t0, *a), (t1, *b) in zip(poses, poses[1:]):
            if t0 <= t <= t1:
                x = (t - t0) / (t1 - t0)
                us, ue = curve(shoulder, t0)(x), curve(elbow, t0)(x)
                s_, f, h, k = a[0] + (b[0] - a[0]) * us, a[1] + (b[1] - a[1]) * ue, a[2] + (b[2] - a[2]) * ue, a[3] + (b[3] - a[3]) * ue
                stretch = max(stretch, abs(k * (1 / a[3] + (1 / b[3] - 1 / a[3]) * ue) - 1))
                break
        world = lambda p: about(S, about(E, about(Wr, p, lambda v: (lambda w: (w[0], w[1] / k))(rot(v, h))), lambda v: rot((v[0], v[1] * k), f)), lambda v: rot(v, s_))
        tip, e, w = world((Wr[0], Wr[1] + 0.09 * H)), world(E), world(Wr)
        ang = abs(math.degrees(math.atan2(-(w[0] - e[0]), w[1] - e[1])))
        if 40 < ang < 140:
            sideways = max(sideways, k * abs(math.sin(math.radians(ang))))
        if any(a + fade / 2 <= t <= c + fade / 2 for a, c in windows):
            palm_side = max(palm_side, abs(math.sin(math.atan2(tip[0] - w[0], tip[1] - w[1]))))
        if prev:
            speed = max(speed, math.dist(tip, prev) * 120 / H)
        prev = tip
    return speed, sideways, stretch, palm_side


