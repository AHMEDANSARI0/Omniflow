def webp_size(path):
    data = open(path, "rb").read()
    if data[:4] != b"RIFF" or data[8:12] != b"WEBP" or data[12:16] != b"VP8X" or not data[20] & 0x10:
        return None  # need the extended format with alpha
    return (1 + int.from_bytes(data[24:27], "little"), 1 + int.from_bytes(data[27:30], "little")), len(data)


