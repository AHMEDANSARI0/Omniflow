def hand_size():
    """open palm vs the arm it sits on (px of the 560 canvas): palm + fingers width / forearm cuff width,
    and hand length / relaxed hand length. A real open hand is about as wide as the wrist."""
    try:
        import numpy as np
        from PIL import Image
    except ImportError:
        return None
    mask = lambda f: np.array(Image.open(ROOT + "public/bot/" + f).convert("RGBA"))[..., 3] > 8
    span = lambda m: [r.nonzero()[0][-1] - r.nonzero()[0][0] + 1 for r in m if r.any()]
    palm_rows, fore, grip = span(mask("omniflow-bot-palm-r.webp")), mask("omniflow-bot-fore-r.webp"), mask("omniflow-bot-hand-r.webp")
    cuff = max(span(fore[int(0.6 * 846):int(0.64 * 846)]))
    grip_rows = np.nonzero(grip.any(axis=1))[0]
    return round(max(palm_rows[len(palm_rows) // 2:]) / cuff, 2), round(len(palm_rows) / (grip_rows[-1] - grip_rows[0] + 1), 2)


